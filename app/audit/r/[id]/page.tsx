function FindingCard({ f }: { f: AuditFinding }) {
  const { Icon, tint } = SEVERITY_ICON[f.severity];
  return (
    <div className="rounded-xl border border-ink-100 bg-white p-5">
      <div className="flex items-center gap-2">
        <span className={`w-7 h-7 rounded-lg ${tint} flex items-center justify-center`}><Icon size={14} strokeWidth={2.4} /></span>
        <span className="text-[11px] uppercase tracking-[.14em] font-bold text-ink-500">{f.area}</span>
      </div>
      <h3 className="mt-3 font-bold text-ink-950 tracking-tight text-[1.02rem]">{f.title}</h3>
      <p className="mt-1 text-[13.5px] text-ink-600 leading-relaxed">{f.body}</p>
    </div>
  );
}

function CompetitorCard({ c }: { c: CompetitiveBenchmark }) {
  return (
    <div className="rounded-xl border border-ink-100 bg-white p-5 flex flex-col">
      <div className="text-[11px] uppercase tracking-[.12em] font-bold text-brand-700">{c.category}</div>
      <h3 className="mt-2 font-extrabold text-ink-950 text-[1.1rem] tracking-tight">{c.name}</h3>
      <p className="mt-3 text-[13.5px] text-ink-600 leading-relaxed">{c.pattern}</p>
      <div className="mt-4 pt-4 border-t border-ink-100 text-[12.5px]">
        <span className="font-bold text-brand-700 uppercase tracking-wider text-[10.5px]">Takeaway · </span>
        <span className="text-ink-700">{c.takeaway}</span>
      </div>
    </div>
  );
}

function RecCard({ r }: { r: AuditRecommendation }) {
  const tone =
    r.priority === 'high'   ? 'border-ink-950 bg-white' :
    r.priority === 'medium' ? 'border-ink-100 bg-white' :
                              'border-ink-100 bg-ink-50/50';
  return (
    <div className={`rounded-xl border-2 ${tone} p-5 md:p-6`}>
      <div className="flex items-center gap-2">
        <span className={`text-[10.5px] uppercase tracking-[.14em] font-bold px-2 py-0.5 rounded-md ${
          r.priority === 'high'   ? 'bg-ink-950 text-white' :
          r.priority === 'medium' ? 'bg-brand-50 text-brand-700' :
                                    'bg-ink-100 text-ink-700'
        }`}>{PRIORITY_LABEL[r.priority]}</span>
      </div>
      <h3 className="mt-3 font-extrabold text-ink-950 text-[1.1rem] tracking-tight">{r.title}</h3>
      <p className="mt-2 text-[14px] text-ink-700 leading-relaxed">{r.body}</p>
      {r.exemplar && (
        <div className="mt-3 pt-3 border-t border-ink-100 text-[12.5px]">
          <span className="font-bold text-ink-800">{r.exemplar.company}: </span>
          <span className="text-ink-600">{r.exemplar.note}</span>
        </div>
      )}
    </div>
  );
}
