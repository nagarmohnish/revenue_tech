import Link from 'next/link';
import { notFound } from 'next/navigation';
import { loadAudit } from '@/lib/audit/store';
import type { AuditFinding, AuditRecommendation, CompetitiveBenchmark } from '@/lib/audit/types';
import {
  Wallet, Sparkles, BarChart3, FileText, ShieldCheck, ArrowRight, Download,
  Check, TriangleAlert, X as XIcon, Lightbulb, ExternalLink,
} from 'lucide-react';

export const dynamic = 'force-dynamic';

const MODEL_LABEL: Record<string, string> = {
  freemium: 'Freemium', trial: 'Free trial', paid_only: 'Paid only',
  usage_based: 'Usage-based', hybrid: 'Hybrid', enterprise_only: 'Enterprise only',
  unknown: 'Unclassified',
};

function gradeBand(s: number) {
  if (s >= 85) return { label: 'Best in class', tone: 'brand' };
  if (s >= 70) return { label: 'Solid',         tone: 'brand' };
  if (s >= 55) return { label: 'Mid-pack',      tone: 'amber' };
  return         { label: 'Below average', tone: 'coral' };
}

const SEVERITY_ICON = {
  good: { Icon: Check,          tint: 'bg-brand-500/10 text-brand-700' },
  warn: { Icon: TriangleAlert,  tint: 'bg-amber-100 text-amber-700'    },
  bad:  { Icon: XIcon,          tint: 'bg-coral-400/10 text-coral-600'  },
} as const;

const PRIORITY_LABEL = { high: 'High leverage', medium: 'Medium', low: 'Polish' };

